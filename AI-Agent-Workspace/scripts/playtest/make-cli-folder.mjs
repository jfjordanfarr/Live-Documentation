#!/usr/bin/env node
// Makes the folder a command-line tester is given (cli-playtest.mjs), 2026-11-22: a copy of the code under question,
// with nothing of this workspace's guidance or records in it, so that no tester reads the guide, the skill, a task's
// key or a record of earlier runs.
//
// Usage: node AI-Agent-Workspace/scripts/playtest/make-cli-folder.mjs --source estate|repository --arm files|cli --out <dir>
//   estate:     the estate sample (tests/integration/programs/csharp/estate) without its `expected/` oracle records.
//   repository: every tracked file of this checkout but the agents' guidance and records (AI-Agent-Workspace/,
//               AGENTS.md, CLAUDE.md, .agents/, .claude/, .github/copilot-instructions.md) and the authored and
//               generated documents under .mdmd/, except the board its configuration names.
//   --arm cli:  the same copy, with its Live Docs generated by the tool over it, as a repository that uses the tool
//               holds them; --arm files leaves the code alone.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const checkout = path.resolve(here, '..', '..', '..');
const args = process.argv.slice(2);
const option = (name) => { const i = args.indexOf(name); return i >= 0 ? args[i + 1] : null; };
const source = option('--source');
const arm = option('--arm');
const out = option('--out') && path.resolve(option('--out'));
if (!['estate', 'repository'].includes(source) || !['files', 'cli'].includes(arm) || !out) {
  console.error('usage: make-cli-folder.mjs --source estate|repository --arm files|cli --out <dir>');
  process.exit(2);
}
if (fs.existsSync(out)) { console.error(`${out} exists; name a new folder`); process.exit(2); }

const withheld = (file) => /^(AI-Agent-Workspace\/|\.agents\/|\.claude\/|AGENTS\.md$|CLAUDE\.md$|\.github\/copilot-instructions\.md$)/.test(file)
  || (file.startsWith('.mdmd/') && file !== '.mdmd/layer-3/board.mdmd.md');

if (source === 'estate') {
  const estate = path.join(checkout, 'tests', 'integration', 'programs', 'csharp', 'estate');
  fs.cpSync(estate, out, { recursive: true, filter: (from) => path.relative(estate, from).split(path.sep)[0] !== 'expected' });
} else {
  const tracked = execFileSync('git', ['ls-files', '-z'], { cwd: checkout, encoding: 'utf8', maxBuffer: 1 << 28 }).split('\0').filter(Boolean);
  for (const file of tracked.filter((f) => !withheld(f))) {
    const from = path.join(checkout, file);
    if (!fs.existsSync(from)) continue; // deleted in the working tree
    fs.mkdirSync(path.dirname(path.join(out, file)), { recursive: true });
    fs.copyFileSync(from, path.join(out, file));
  }
}
if (arm === 'cli') {
  execFileSync(path.join(here, 'live-docs'), ['generate'], { cwd: out, stdio: ['ignore', 'ignore', 'inherit'] });
}
console.log(out);
