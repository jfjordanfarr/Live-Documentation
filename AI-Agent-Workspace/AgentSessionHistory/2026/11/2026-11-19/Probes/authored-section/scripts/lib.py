"""Shared readers for the authored-section probe: a Live Doc's authored block, and a source file's opening comment.

Run from the repository root; see ../README.md for the definitions these functions implement.
"""
import json
import os
import re

BINARY = {".png", ".jpg", ".gif", ".ico", ".wav", ".mp4", ".woff", ".woff2", ".ttf", ".wasm"}
NO_SYNTAX = {".json", ".txt", ".patch", ".nvmrc"}  # strict JSON and plain text carry no comment of their own
C_STYLE = {".ts", ".tsx", ".js", ".mjs", ".cjs", ".jsx", ".cs", ".java", ".rs", ".go", ".c", ".h", ".hpp", ".cpp", ".css", ".mod", ".less", ".scss"}
HASH = {".py", ".rb", ".sh", ".yml", ".yaml", ".toml", ".gitignore", ".gitattributes", ".env", ".ps1", ".psm1", ".psd1"}
MARKUP = {".xml", ".csproj", ".config", ".html", ".aspx", ".ascx", ".cshtml", ".sqlproj", ".resx", ".master"}
SQL = {".sql", ".sqldataprovider"}

# Comments that instruct a tool rather than describe the file.
DIRECTIVE = re.compile(
    r"^\s*(eslint|@ts-|prettier|#region|#endregion|@vitest-environment|istanbul|c8 |jshint|global |"
    r"frozen_string_literal|-\*-|encoding[:=]|coding[:=]|#requires|requires -|@jsx|"
    r"<auto-generated|auto-generated|this code was generated|copyright|spdx-license|licensed |"
    r"\(c\)|all rights reserved|see the license|license(d)? under|stylelint|go:build|\+build|"
    r"visual studio version|minimumvisualstudioversion|resharper|pragma|live documentation: )",
    re.I)


def config():
    with open(".live-docs.config.json", encoding="utf8") as handle:
        return json.load(handle)


def live_docs():
    """Every Live Doc: (source path, doc path)."""
    cfg = config()
    base = os.path.join(cfg["root"], cfg["baseLayer"])
    suffix = cfg["extension"]
    out = []
    for folder, _, files in os.walk(base):
        for name in files:
            if name.endswith(suffix):
                doc = os.path.join(folder, name)
                out.append((os.path.relpath(doc, base)[: -len(suffix)], doc))
    return sorted(out)


def ext_of(path):
    name = os.path.basename(path)
    if name.startswith(".") and name.count(".") == 1:
        return name.lower()
    return os.path.splitext(name)[1].lower() or "(none)"


PLACEHOLDER = re.compile(r"_Pending( authored purpose| notes| purpose)?_|_No reader handles this kind of file yet[^_]*_", re.I)


def authored_sections(doc_text):
    """The authored block's sections as {heading: body}; words before any heading under ''."""
    match = re.search(r"^## Authored[ \t]*$(.*?)^## (Generated|Declared)[ \t]*$", doc_text, re.M | re.S)
    if not match:
        return None
    sections, heading, lines = {}, "", []
    for line in match.group(1).strip("\n").split("\n"):
        head = re.match(r"^###\s+(.*?)\s*$", line)
        if head:
            sections[heading] = "\n".join(lines).strip()
            heading, lines = head.group(1), []
        else:
            lines.append(line)
    sections[heading] = "\n".join(lines).strip()
    return {k: v for k, v in sections.items() if k or v}


def meaningful(body):
    return bool(body) and bool(PLACEHOLDER.sub("", body).strip())


def _strip_c_comment(block):
    lines = []
    for line in block.split("\n"):
        line = re.sub(r"^\s*(/\*\*?|\*/|\*(?!/)|//[/!]?)\s?", "", line)
        line = re.sub(r"\*/\s*$", "", line)
        lines.append(line.rstrip())
    return "\n".join(lines).strip()


def _all_directive(text):
    lines = [l for l in text.split("\n") if l.strip()]
    return bool(lines) and all(DIRECTIVE.search(l) for l in lines)


ATTACH = re.compile(
    r"^\s*(export\b|default\b|async\b|function\b|class\b|const\b|let\b|var\b|interface\b|type\b|enum\b|declare\b|abstract\b|"
    r"public\b|private\b|internal\b|protected\b|static\b|sealed\b|partial\b|pub\b|fn\b|struct\b|impl\b|trait\b|func\b|"
    r"\[|@[A-Za-z]|[A-Za-z_][\w:<>\s\*&]*\([^;]*$|[.#:\w-][^{;]*\{)")


def opening_comment(path, text):
    """(state, text) where state is 'file' (a file-level comment), 'attached' (a leading comment that documents the
    first declaration rather than the file), 'directive' (only tool directives), 'none', 'no-syntax' or 'binary'."""
    ext = ext_of(path)
    if ext in BINARY:
        return "binary", ""
    if ext in NO_SYNTAX:
        if os.path.basename(path).startswith("tsconfig") and re.match(r"\s*(//|/\*)", text):
            return "file", ""
        return "no-syntax", ""
    text = text.lstrip("﻿").replace("\r\n", "\n")
    if ext in C_STYLE:
        return _c_style(text, ext)
    if ext in HASH:
        return _hash_style(text, ext)
    if ext in SQL:
        return _sql(text)
    if ext in MARKUP:
        return _markup(text)
    if ext == ".sln":
        return "directive", ""
    return "none", ""


IMPORTISH = re.compile(r"^(import\b|using\b|package\b|namespace\b|#include|#pragma|#ifndef|#define|use\b|mod\b|module\b|extern\b|"
                       r"@import|@use|@charset|require\(|\"use strict\"|'use strict')")


def _c_style(text, ext):
    """Leading comments, grouped into runs that blank lines separate. Every run but the last belongs to the file; the
    last does too unless it sits directly on a declaration (then it is that declaration's doc), except that a Rust
    `//!` and a JSDoc `@module`/`@file`/`@fileoverview`/`@packageDocumentation` always belong to the file."""
    pos, runs = 0, []
    if text.startswith("#!"):
        pos = text.find("\n") + 1
    while True:
        rest = text[pos:]
        stripped = rest.lstrip()
        skipped = rest[: len(rest) - len(stripped)]
        pos += len(skipped)
        if stripped.startswith("/*"):
            end = stripped.find("*/")
            end = len(stripped) if end < 0 else end + 2
        elif stripped.startswith("//"):
            end = stripped.find("\n")
            end = len(stripped) if end < 0 else end
        else:
            break
        if not runs or skipped.count("\n") >= 2:
            runs.append([])
        runs[-1].append(stripped[:end])
        pos += end
    if not runs:
        return "none", ""
    after = text[pos:]
    next_line = after.strip().split("\n", 1)[0] if after.strip() else ""
    blank_after = after[: len(after) - len(after.lstrip())].count("\n") >= 2
    last_attached = not blank_after and next_line and not IMPORTISH.match(next_line) and ATTACH.match(next_line)
    file_runs = runs[:-1] if last_attached else runs
    for run in runs:
        raw = "\n".join(run)
        if (ext == ".rs" and "//!" in raw) or re.search(r"@(module|file|fileoverview|packageDocumentation)\b", raw):
            if run not in file_runs:
                file_runs = file_runs + [run]
    words = [w for w in (_strip_c_comment("\n".join(r)) for r in file_runs) if w and not _all_directive(w)]
    if words:
        return "file", "\n".join(words)
    if last_attached and not _all_directive(_strip_c_comment("\n".join(runs[-1]))):
        return "attached", _strip_c_comment("\n".join(runs[-1]))
    return "directive", ""


def _hash_style(text, ext):
    lines = text.split("\n")
    i = 0
    if lines and lines[0].startswith("#!"):
        i = 1
    if ext == ".py":
        while i < len(lines) and (not lines[i].strip() or lines[i].lstrip().startswith("#")):
            i += 1
        head = [l.lstrip("# ").rstrip() for l in lines[:i] if l.lstrip().startswith("#") and not l.startswith("#!")]
        head = [h for h in head if h and not DIRECTIVE.search(h)]
        rest = "\n".join(lines[i:]).lstrip()
        doc = re.match(r'^[rRuU]?("""|\'\'\'|"|\')(.*?)\1', rest, re.S)
        if doc:
            return "file", ("\n".join(head) + "\n" + doc.group(2)).strip()
        return ("file", "\n".join(head)) if head else ("none", "")
    if ext in {".ps1", ".psm1", ".psd1"}:
        return _powershell(text)
    head = []
    while i < len(lines) and (not lines[i].strip() or lines[i].lstrip().startswith("#")):
        if lines[i].strip():
            head.append(lines[i].lstrip("# ").rstrip())
        i += 1
    head = [h for h in head if h and not DIRECTIVE.search(h)]
    if not head:
        return "none", ""
    if ext == ".rb" and i < len(lines) and re.match(r"\s*(class|module|def)\b", lines[i]) and not (i > 0 and not lines[i - 1].strip()):
        return "attached", "\n".join(head)
    return "file", "\n".join(head)


def _powershell(text):
    """Leading `#` lines or a `<# #>` block before the first statement; `help` when it carries .SYNOPSIS or .DESCRIPTION.
    A help block inside the file's first function, with nothing above it, is reported as 'function-help'."""
    rest = text
    head = []
    while True:
        stripped = rest.lstrip()
        if stripped.startswith("<#"):
            end = stripped.find("#>")
            end = len(stripped) if end < 0 else end + 2
            head.append(stripped[2:end - 2])
            rest = stripped[end:]
        elif stripped.startswith("#"):
            end = stripped.find("\n")
            end = len(stripped) if end < 0 else end
            head.append(stripped[1:end])
            rest = stripped[end:]
        else:
            break
    words = "\n".join(h.strip() for h in head if h.strip() and not DIRECTIVE.search(h.strip()))
    if words:
        return ("help" if re.search(r"^\s*\.(SYNOPSIS|DESCRIPTION)\b", words, re.M | re.I) else "file"), words
    first = re.match(r"\s*function\s+[\w-]+\s*(\([^)]*\))?\s*\{\s*<#(.*?)#>", rest, re.S | re.I)
    if first and re.search(r"\.(SYNOPSIS|DESCRIPTION)\b", first.group(2), re.I):
        return "function-help", first.group(2).strip()
    return ("directive", "") if head else ("none", "")


def _sql(text):
    rest, head = text, []
    while True:
        stripped = rest.lstrip()
        if stripped.startswith("/*"):
            end = stripped.find("*/")
            end = len(stripped) if end < 0 else end + 2
            head.append(_strip_c_comment(stripped[:end]))
            rest = stripped[end:]
        elif stripped.startswith("--"):
            end = stripped.find("\n")
            end = len(stripped) if end < 0 else end
            head.append(stripped[2:end].strip())
            rest = stripped[end:]
        else:
            break
    words = "\n".join(h for h in head if h and not DIRECTIVE.search(h) and not re.fullmatch(r"[-=*\s]+", h))
    return ("file", words) if words else (("directive", "") if head else ("none", ""))


def _markup(text):
    rest = re.sub(r"^\s*<\?xml[^>]*\?>", "", text)
    rest = re.sub(r"^\s*<%@[^%]*%>", "", rest)
    m = re.match(r"\s*(<!--(.*?)-->|<%--(.*?)--%>|@\*(.*?)\*@)", rest, re.S)
    if not m:
        return "none", ""
    words = next(g for g in m.groups()[1:] if g is not None).strip()
    return ("file", words) if words and not _all_directive(words) else ("directive", "")


def sentences(text):
    """Split prose into claims: markdown bullets, then sentences."""
    out = []
    for block in re.split(r"\n(?=\s*[-*] )|\n\s*\n", text):
        block = re.sub(r"^\s*[-*]\s+", "", block).replace("\n", " ").strip()
        out.extend(s.strip() for s in re.split(r"(?<=[.;!?])\s+(?=[A-Z\[`(])", block) if s.strip())
    return out
